def get_mission_help(number: int, player_count: int = 3) -> Dict:
    mission = get_mission(number, 3)
    if isinstance(player_count, bool) or not isinstance(player_count, int) or not 2 <= player_count <= 5:
        raise ValueError("Bomb Busters requires 2 to 5 players")
    supported = player_count >= mission["min_players"]
    setup_players = player_count if supported else mission["min_players"]
    mission = get_mission(number, setup_players)
    detail = copy.deepcopy(MISSION_HELP[number])
    wire_setup = {
        "zh": f"{setup_players} 人开局配置：蓝线(🔵)1 至 {mission['blue_max']} 各四条。"
              f"黄线(🟡){mission['yellow_count']} 条，黄色候选 {mission['yellow_pool']} 个。"
              f"红线(🔴){mission['red_count']} 条，红色候选 {mission['red_pool']} 个。",
        "en": f"Initial setup for {setup_players}: four blue wires (🔵) each of values 1–{mission['blue_max']}. "
              f"Yellow wires (🟡): {mission['yellow_count']} from {mission['yellow_pool']} candidates. "
              f"Red wires (🔴): {mission['red_count']} from {mission['red_pool']} candidates.",
    }
    sections = []
    for key, label in (
        ("setup", ("准备与配线", "Setup")),
        ("difference", ("本关与普通规则的差别", "What changes")),
        ("play", ("回合怎样进行", "How to play")),
        ("warning", ("限制与失败条件", "Restrictions and risks")),
        ("example", ("具体例子", "Example")),
    ):
        text = detail.get(key) if key != "difference" else {"zh": mission["rules_zh"], "en": mission["rules"]}
        if key == "setup":
            text = {language: f"{wire_setup[language]} {text[language]}" for language in ("zh", "en")}
        sections.append({"id": key, "label": {"zh": label[0], "en": label[1]}, "text": text})
    constraints = []
    if number in (31, 32, 34, 37, 42, 57, 61, 66):
        letters = "ABCDE" if number in (31, 34, 66) else "ABCDEFGHIJKL"
        constraints = [{"id": letter, "text": {"zh": CONSTRAINT_HELP[letter][0],
                       "en": CONSTRAINT_HELP[letter][1]}} for letter in letters]
    return {
        "id": number, "title": detail["title"], "player_count": player_count,
        "setup_players": setup_players, "supported": supported, "min_players": mission["min_players"],
        "audio_companion": mission["audio_companion"], "source_status": "community_transcribed",
        "sections": sections, "constraints": constraints,
        "challenges": [{"id": key, "text": {"zh": value[0], "en": value[1]}}
                       for key, value in CHALLENGE_HELP.items()] if number in (55, 60) else [],
    }


if set(MISSION_HELP) != set(range(1, MISSION_COUNT + 1)):
    raise ValueError("Bomb Busters mission Help is incomplete")
